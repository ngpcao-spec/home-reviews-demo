-- Authorized maintenance barrier. No reviews/reports are deleted here.
create table public.review_corpus_policy(
 id boolean primary key default true check(id),
 version text not null default 'recent_text_100_6m_v1',
 paused boolean not null default true,
 enabled boolean not null default false,
 max_text_reviews integer not null default 100 check(max_text_reviews=100),
 months integer not null default 6 check(months=6),
 timezone text not null default 'Asia/Ho_Chi_Minh',
 epoch uuid not null default gen_random_uuid(),
 activated_at timestamptz,
 retired_relations text[] not null default '{}',
 updated_at timestamptz not null default now()
);
insert into public.review_corpus_policy(id) values(true);
alter table public.review_corpus_policy enable row level security;
revoke all on public.review_corpus_policy from public,anon,authenticated,service_role;
grant select on public.review_corpus_policy to authenticated;
grant select,update on public.review_corpus_policy to service_role;
create policy authenticated_policy_read on public.review_corpus_policy for select to authenticated using(true);

create table private.retention_cron_restore(jobid bigint primary key,jobname text,was_active boolean not null);
revoke all on private.retention_cron_restore from public,anon,authenticated,service_role;
insert into private.retention_cron_restore select jobid,jobname,active from cron.job on conflict do nothing;
do $$declare j record;begin for j in select jobid from cron.job where active loop perform cron.alter_job(j.jobid,active:=false);end loop;end $$;

create function public.retention_write_guard() returns trigger language plpgsql set search_path='' as $$
declare p public.review_corpus_policy;begin
 if current_user in('postgres','supabase_admin') and current_setting('home.retention_maintenance',true)='on' then return null;end if;
 select * into strict p from public.review_corpus_policy where id for share;
 if p.paused then raise exception 'RETENTION_TRANSITION_ACTIVE';end if;
 if (tg_table_schema||'.'||tg_table_name)=any(p.retired_relations) then raise exception 'REPORT_PIPELINE_RETIRED';end if;
 return null;
end $$;
