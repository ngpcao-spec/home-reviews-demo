import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import path from 'node:path';
import {it,expect,vi,afterAll,beforeAll} from 'vitest';
import {batchSolDraft} from '../../supabase/functions/_shared/jev-batch-experiment';
import {PRIORITY_SELECTOR_VERSION,evidenceSelectorBinding} from '../../supabase/functions/_shared/report-evidence-selector';
import {analysisTextSha256} from '../../supabase/functions/_shared/analysis-text';
const root=process.env.HOME_REVIEWS_SELECTOR_REPLAY_ROOT;
if(!root||!existsSync(root))throw Error('HOME_REVIEWS_SELECTOR_REPLAY_ROOT must point to the saved sol-priority-experiment-20261026 directory. No network fallback.');
const prior=path.resolve(root,'../sol-evidence-priority-20261026/corpora');
const manifest=JSON.parse(readFileSync('tests/fixtures/sol-priority-frozen-manifest.json','utf8'));
const results:unknown[]=[];let deny:ReturnType<typeof vi.spyOn>;
beforeAll(()=>{deny=vi.spyOn(globalThis,'fetch').mockRejectedValue(Error('NETWORK_FORBIDDEN'));});
afterAll(()=>{expect(deny).not.toHaveBeenCalled();deny.mockRestore();writeFileSync(path.join(root!,'integration-replay.json'),JSON.stringify({version:PRIORITY_SELECTOR_VERSION,provider_calls:0,results},null,2));});
for(const d of manifest.corpora)it('reproduces the exact real frozen associations and Sol wire in the normal shared worker: '+d.name,async()=>{
 const c=JSON.parse(readFileSync(path.join(prior,d.slug+'.json'),'utf8'));
 const f=JSON.parse(readFileSync(path.join(root!,'frozen-'+d.slug+'.json'),'utf8'));
 const input=structuredClone(c),oldDraft=await batchSolDraft(c.run,c.tasks);
 expect(oldDraft.request_json).toBe(c.run.envelope.request_json);
 c.run.template.evidence_selector=await evidenceSelectorBinding(PRIORITY_SELECTOR_VERSION);
 const draft=await batchSolDraft(c.run,c.tasks);
 expect(draft.evidence).toEqual(f.envelope.evidence);
 expect(draft.evidence.map(e=>({evidence_id:e.evidence_id,review_id:e.review_id,category:e.category,polarity:e.polarity}))).toEqual(d.ordered_associations);
 expect(draft.packet).toEqual(f.envelope.packet);expect(draft.compact_manifest).toEqual(f.envelope.compact_manifest);
 expect(draft.request_json).toBe(f.envelope.request_json);expect(await analysisTextSha256(draft.request_json)).toBe(d.request_sha256);
 expect(draft.statistics).toEqual(f.envelope.statistics);expect(draft.counts).toEqual(f.envelope.counts);
 expect(c.tasks).toEqual(input.tasks);expect(c.run.snapshot).toEqual(input.run.snapshot);
 const id=d.slug==='khouse'?'89eadd38':d.slug==='bottega26'?'d2838f11':'5ee0e75b';
 expect(draft.evidence.some(e=>e.review_id.startsWith(id)&&e.category==='quality'&&e.polarity==='negative')).toBe(true);
 results.push({slug:d.slug,experiment_id:d.experiment_id,associations:draft.evidence.length,ordered_associations_exact:true,wire_exact:true,request_sha256:d.request_sha256,statistics_unchanged:true,native_receipts_unchanged:true,legacy_wire_exact:true,critical_quality_binding:id});
},60000);
