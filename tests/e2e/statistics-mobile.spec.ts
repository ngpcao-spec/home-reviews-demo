test('slow response is canceled when the period changes; loading is explicit',async({page})=>{
 let release!:()=>void
 const gate=new Promise<void>(resolve=>{release=resolve})
 await page.route('**/__statistics',async route=>{
  if(route.request().postDataJSON().args.p_period==='3m'){await gate;if(route.request().failure())return}
  await route.continue().catch(()=>{})
 })
 await page.goto('/tests/e2e/fixtures/analysis-mobile.html?tab=statistics')
 await expect(page.getByRole('status')).toHaveText('Chargement…')
 await page.getByRole('button',{name:'Tout',exact:true}).click()
 await expect(page.locator('.statistics-metrics button').first()).toContainText('1 205')
 release()
 await expect(page.getByRole('button',{name:'Tout',exact:true})).toHaveAttribute('aria-pressed','true')
 await expect(page.locator('.statistics-metrics button').first()).toContainText('1 205')
})
