import { test, expect } from "@playwright/test";
for(const language of ["fr","vi"]) test(`prioritized ${language}: observation/action, source expansion, reload and closed spending`,async({page})=>{
  if(test.info().project.name==="desktop")await page.setViewportSize({width:768,height:1024});
  const paid:string[]=[];
  page.on("request",r=>{if(r.method()==="POST"||/api\.openai|api\.jev|apify|process-jev-luna-sol/.test(r.url()))paid.push(r.url());});
  await page.goto(`/tests/e2e/fixtures/jls-prioritized.html?language=${language}`);
  await expect(page.getByText("EXPLICIT SYNTHETIC TEST — NO REAL SOL RESULT")).toBeVisible();
  const button=page.getByRole("button",{name:language==="fr"?"Nouvel essai — GO explicite requis":"Thử nghiệm mới — cần cho phép rõ ràng"});
  await expect(button).toBeDisabled();
  await expect(page.getByText(language==="fr"?"Mécanisme prêt — aucun GO enregistré":"Cơ chế sẵn sàng — chưa ghi nhận cho phép chạy")).toBeVisible();
  await expect(page.getByText(language==="fr"?"Ce que les clients rapportent":"Nội dung khách hàng phản ánh")).toBeVisible();
  await expect(page.getByText(language==="fr"?"Action proposée au restaurateur":"Hành động đề xuất cho nhà hàng")).toBeVisible();
  await page.getByText(language==="fr"?"Consulter la preuve et son contexte":"Xem bằng chứng và ngữ cảnh",{exact:true}).click();
  await expect(page.locator("details").filter({has:page.getByText(language==="fr"?"Consulter la preuve et son contexte":"Xem bằng chứng và ngữ cảnh",{exact:true})}).locator("blockquote").first()).toContainText("waited");
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  await page.reload();await expect(button).toBeDisabled();
  await expect(page.getByText(language==="fr"?"Note méthodologique":"Ghi chú phương pháp").last()).toBeVisible();
  expect(paid).toEqual([]);
  await page.goto(`/tests/e2e/fixtures/jls-prioritized.html?language=${language}&state=completed`);
  await expect(page.getByText("gpt-6.1-sol",{exact:true})).toBeVisible();
  await page.getByText(language==="fr"?"Réponse brute et contrôles — sans nouvel appel":"Phản hồi gốc và kiểm tra — không gọi thêm",{exact:true}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  expect(paid).toEqual([]);
  await page.screenshot({path:`test-results/prioritized-${language}-${test.info().project.name}.png`,fullPage:true});
  await page.goto(`/tests/e2e/fixtures/jls-prioritized.html?language=${language}&state=revalidated`);
  await expect(page.getByTestId("prioritized-revalidation")).toContainText("jls-prioritized-disclosure-v1.1");
  await expect(page.getByText(language==="fr"?"Statut historique : needs_review":"Trạng thái lịch sử: needs_review",{exact:true})).toBeVisible();
  await page.getByTestId("prioritized-original").locator("summary").first().click();
  await expect(page.getByTestId("prioritized-original")).toContainText(language==="fr"?"Recommandations proposées":"Khuyến nghị đề xuất");
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  await page.reload();await expect(page.getByTestId("prioritized-revalidation")).toBeVisible();
  expect(paid).toEqual([]);
  await page.screenshot({path:`test-results/prioritized-revalidation-${language}-${test.info().project.name}.png`,fullPage:true});
  const future=page.getByTestId("editorial-preparation");
  await expect(future.getByRole("button")).toBeDisabled();
  await expect(future).toContainText(language==="fr"?"Exemple synthétique — aucun rapport généré":"Ví dụ giả lập — chưa tạo báo cáo");
  await future.getByText(language==="fr"?"Couverture des critiques — tous les thèmes":"Bao phủ phản ánh tiêu cực — tất cả chủ đề",{exact:true}).click();
  await expect(future.locator("article")).toHaveCount(25);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  expect(paid).toEqual([]);
  await page.screenshot({path:`test-results/editorial-${language}-${test.info().project.name}.png`,fullPage:true});
});
